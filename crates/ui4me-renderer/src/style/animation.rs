//! owner: 006-style-engine — T087–T089 (L-ANIM-r5).
//!
//! CSS Transitions 1 and CSS Animations 1 on Stylo's animation machinery (research R-11; AD-11,
//! AD-44; FR-062–FR-067). [`StyleBridge`](crate::style::traverse::StyleBridge) owns one
//! [`AnimationEngine`] per document: Stylo's `DocumentAnimationSet` (the per-element sets of
//! transitions and `@keyframes` animations, created and cancelled inside the style pass), the
//! document animation time (005's clock supplies it before each pass) and the queue of generated
//! events.
//!
//! What Stylo does (servo build): starts and cancels transitions and animations during the
//! style pass (`process_animations`), interpolates with the CSS timing functions (cubic-bezier,
//! steps), applies fill modes, direction and iteration, and recascades the element with the
//! interpolated declarations at the current time. What it leaves to the embedder (Servo's script
//! crate does it there) and what this module supplies:
//!
//! * **the tick**: `Pending → Running → Finished` states, iteration steps, and the restyle hints
//!   that make the next pass re-sample values ([`AnimationEngine::tick`]);
//! * **events** by diffing per-element state at each tick and each pass; they are queued, never
//!   dispatched here (FR-066, FR-070: a style update calls no host code). 012 dispatches them as
//!   idle work in turn step 4;
//! * **fill-forwards**: Stylo drops a `Finished` animation from the set on the next pass, which
//!   would lose the `forwards`/`both` fill value. A finished animation with such a fill is held
//!   in `Paused(end progress)`, which keeps applying the end keyframe, needs no ticks and fires no
//!   second `animationend`;
//! * **disconnection** (FR-067): a set whose element is no longer connected, or whose arena slot
//!   was reused, is discarded without events; a re-inserted subtree starts from its current
//!   computed value (it has no previous style, so no transition starts).

use std::collections::HashSet;
use style::animation::{
    Animation, AnimationSetKey, AnimationState, DocumentAnimationSet, ElementAnimationSet,
    KeyframesIterationState, Transition,
};
use style::selector_parser::PseudoElement;
use ui4me_document::document::Document;
use ui4me_engine_types::ids::NodeId;

/// The eight events of CSS Transitions 1 and CSS Animations 1 (012 `event-types.md`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum AnimationEventKind {
    TransitionRun,
    TransitionStart,
    TransitionEnd,
    TransitionCancel,
    AnimationStart,
    AnimationIteration,
    AnimationEnd,
    AnimationCancel,
}

impl AnimationEventKind {
    pub const fn event_type(self) -> &'static str {
        match self {
            AnimationEventKind::TransitionRun => "transitionrun",
            AnimationEventKind::TransitionStart => "transitionstart",
            AnimationEventKind::TransitionEnd => "transitionend",
            AnimationEventKind::TransitionCancel => "transitioncancel",
            AnimationEventKind::AnimationStart => "animationstart",
            AnimationEventKind::AnimationIteration => "animationiteration",
            AnimationEventKind::AnimationEnd => "animationend",
            AnimationEventKind::AnimationCancel => "animationcancel",
        }
    }

    pub const fn is_transition(self) -> bool {
        matches!(
            self,
            AnimationEventKind::TransitionRun
                | AnimationEventKind::TransitionStart
                | AnimationEventKind::TransitionEnd
                | AnimationEventKind::TransitionCancel
        )
    }

    /// `transitionend`... all eight bubble (CSS Transitions 1 §events; CSS Animations 1 §events),
    /// none is cancelable.
    pub const fn bubbles(self) -> bool {
        true
    }
}

/// One generated event, queued for 012 (turn step 4). `name` is the `propertyName` of a
/// transition event and the `animationName` of an animation event; `elapsed_time` is in seconds.
#[derive(Clone, Debug, PartialEq)]
pub struct AnimationEvent {
    pub node: NodeId,
    pub kind: AnimationEventKind,
    pub name: String,
    pub elapsed_time: f64,
    /// `""` for the element itself, else `"::before"` or `"::after"`.
    pub pseudo_element: &'static str,
}

/// One transition or animation in force (the `animation_clock` probe).
#[derive(Clone, Debug, PartialEq)]
pub struct ActiveInfo {
    pub node: NodeId,
    /// The property of a transition, the name of an animation.
    pub property: String,
    pub is_animation: bool,
    pub start_ms: f64,
    pub end_ms: f64,
}

/// What a tick changed.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct TickOutcome {
    /// Elements whose values (or state) changed: they are restyled by the next pass.
    pub changed: Vec<NodeId>,
    /// Events generated by this tick (also queued in the engine).
    pub events: usize,
    /// Some transition or animation still needs ticks.
    pub active: bool,
}

pub(crate) struct AnimationEngine {
    pub(crate) set: DocumentAnimationSet,
    /// Document animation time in seconds (`current_time_for_animations`).
    pub(crate) time_s: f64,
    events: Vec<AnimationEvent>,
}

impl Default for AnimationEngine {
    fn default() -> Self {
        AnimationEngine {
            set: DocumentAnimationSet::default(),
            time_s: 0.0,
            events: Vec::new(),
        }
    }
}

fn pseudo_name(p: &Option<PseudoElement>) -> &'static str {
    match p {
        Some(PseudoElement::Before) => "::before",
        Some(PseudoElement::After) => "::after",
        _ => "",
    }
}

/// The live element a set key names: the slot still holds the same generation, the node is an
/// element and it is connected (FR-067).
fn resolve(doc: &Document, key: &AnimationSetKey) -> Option<NodeId> {
    let k = key.node.0 as u64;
    let (index, generation) = ((k & 0xffff_ffff) as usize, (k >> 32) as u32);
    let arena = doc.arena();
    let id = arena.id_at(index)?;
    (id.raw().generation.get() == generation
        && arena.node(id).is_element()
        && arena.is_connected(id))
    .then_some(id)
}

fn key_of(node: NodeId, pseudo: Option<PseudoElement>) -> AnimationSetKey {
    AnimationSetKey::new(
        style::dom::OpaqueNode(
            ui4me_engine_types::ids::OpaqueStyleKey::of(node)
                .get()
                .get() as usize,
        ),
        pseudo,
    )
}

/// `elapsedTime` of `transitionrun` and `transitionstart`: `max(min(-delay, duration), 0)`.
fn transition_start_elapsed(t: &Transition) -> f64 {
    // `+ 0.0` turns a negative zero into 0.
    (-t.delay).clamp(0.0, t.property_animation.duration) + 0.0
}

/// Seconds the transition's active time has run at `now`, clamped to `[0, duration]`.
fn transition_elapsed(t: &Transition, now: f64) -> f64 {
    (now - t.start_time).clamp(0.0, t.property_animation.duration)
}

fn current_iteration(a: &Animation) -> f64 {
    match a.iteration_state {
        KeyframesIterationState::Finite(cur, _) | KeyframesIterationState::Infinite(cur) => cur,
    }
}

/// Active duration in seconds (`None` for an infinite iteration count).
fn active_duration(a: &Animation) -> Option<f64> {
    match a.iteration_state {
        KeyframesIterationState::Finite(_, max) => Some(max * a.duration),
        KeyframesIterationState::Infinite(_) => None,
    }
}

/// `forwards` and `both` keep the end keyframe applied after the end.
fn fills_forwards(a: &Animation) -> bool {
    use style::properties::longhands::animation_fill_mode::computed_value::single_value::T as F;
    matches!(a.fill_mode, F::Forwards | F::Both)
}

impl AnimationEngine {
    pub(crate) fn push(
        &mut self,
        node: NodeId,
        pseudo: &Option<PseudoElement>,
        kind: AnimationEventKind,
        name: String,
        elapsed_time: f64,
    ) {
        self.events.push(AnimationEvent {
            node,
            kind,
            name,
            elapsed_time,
            pseudo_element: pseudo_name(pseudo),
        });
    }

    /// Whether any transition or animation still needs ticks (`needs_animation_ticks`, R-11).
    pub(crate) fn needs_ticks(&self) -> bool {
        self.set
            .sets
            .read()
            .values()
            .any(ElementAnimationSet::needs_animation_ticks)
    }

    /// Cancel every animation whose iteration count is infinite (`Animation.cancel()`); returns the
    /// elements whose animations were cancelled. An infinite animation has no end state, so the
    /// reference page's `end-state` policy cancels it: the element shows its un-animated style.
    pub(crate) fn cancel_infinite(&mut self, doc: &Document) -> Vec<NodeId> {
        let mut nodes = Vec::new();
        for (key, set) in self.set.sets.write().iter_mut() {
            let mut any = false;
            for a in set.animations.iter_mut().filter(|a| {
                matches!(a.iteration_state, KeyframesIterationState::Infinite(_))
                    && !matches!(a.state, AnimationState::Canceled | AnimationState::Finished)
            }) {
                a.state = AnimationState::Canceled;
                any = true;
            }
            if any {
                set.dirty = true;
                if let Some(n) = resolve(doc, key) {
                    nodes.push(n);
                }
            }
        }
        nodes
    }

    /// Mark every set dirty: the next pass re-applies the interpolated declarations (the element
    /// data was cleared, e.g. by a stylesheet change, and the cascade starts without them).
    pub(crate) fn mark_all_dirty(&self) {
        for s in self.set.sets.write().values_mut() {
            s.dirty = true;
        }
    }

    /// Discard the sets of elements that are no longer connected (or whose slot was reused), with
    /// no events.
    pub(crate) fn discard_disconnected(&self, doc: &Document) {
        let mut sets = self.set.sets.write();
        if sets.is_empty() {
            return;
        }
        sets.retain(|k, _| resolve(doc, k).is_some());
    }

    /// Cancel every transition and animation of `nodes` (the next `after_pass` reports them).
    pub(crate) fn cancel_nodes(&mut self, nodes: &[NodeId]) {
        let keys: HashSet<usize> = nodes
            .iter()
            .map(|&n| ui4me_engine_types::ids::OpaqueStyleKey::of(n).get().get() as usize)
            .collect();
        for (k, set) in self.set.sets.write().iter_mut() {
            if !keys.contains(&k.node.0) {
                continue;
            }
            for a in set.animations.iter_mut() {
                a.state = AnimationState::Canceled;
            }
            for t in set.transitions.iter_mut() {
                t.state = AnimationState::Canceled;
            }
            set.dirty = true;
        }
    }

    /// The connected elements (not pseudo-elements) with a CSS animation that is still in force.
    pub(crate) fn elements_with_css_animations(&self, doc: &Document) -> Vec<NodeId> {
        self.set
            .sets
            .read()
            .iter()
            .filter(|(k, set)| {
                k.pseudo_element.is_none()
                    && set.animations.iter().any(|a| {
                        !matches!(a.state, AnimationState::Canceled | AnimationState::Finished)
                    })
            })
            .filter_map(|(k, _)| resolve(doc, k))
            .collect()
    }

    /// Cancel the CSS animations of `node` whose name is not in `names` (its `animation-name` in
    /// force); returns whether any was cancelled.
    pub(crate) fn cancel_unlisted(&mut self, node: NodeId, names: &[String]) -> bool {
        let key = key_of(node, None);
        let mut sets = self.set.sets.write();
        let Some(set) = sets.get_mut(&key) else {
            return false;
        };
        let mut any = false;
        for a in set.animations.iter_mut().filter(|a| {
            !matches!(a.state, AnimationState::Canceled | AnimationState::Finished)
                && !names.iter().any(|n| n.as_str() == &*a.name.to_string())
        }) {
            a.state = AnimationState::Canceled;
            any = true;
        }
        if any {
            set.dirty = true;
        }
        any
    }

    /// Discard the sets of `nodes` (a re-inserted subtree starts afresh), with no events.
    pub(crate) fn discard_nodes(&self, nodes: &[NodeId]) {
        let mut sets = self.set.sets.write();
        if sets.is_empty() {
            return;
        }
        let keys: HashSet<usize> = nodes
            .iter()
            .map(|&n| ui4me_engine_types::ids::OpaqueStyleKey::of(n).get().get() as usize)
            .collect();
        sets.retain(|k, _| !keys.contains(&k.node.0));
    }

    /// The elements with a transition or animation in force (running, delayed or held by a fill).
    pub(crate) fn animating(&self, doc: &Document) -> HashSet<NodeId> {
        self.set
            .sets
            .read()
            .iter()
            .filter(|(_, s)| s.has_active_animation() || s.has_active_transition())
            .filter_map(|(k, _)| resolve(doc, k))
            .collect()
    }

    /// The transitions and animations in force, for the `animation_clock` probe: sorted by
    /// element slot, kind and property or animation name. An infinite animation has no end
    /// (`end_ms` is `f64::INFINITY`).
    pub(crate) fn active_list(&self, doc: &Document) -> Vec<ActiveInfo> {
        let mut out = Vec::new();
        for (key, s) in self.set.sets.read().iter() {
            let Some(node) = resolve(doc, key) else {
                continue;
            };
            for t in s.transitions.iter().filter(|t| {
                t.state != AnimationState::Canceled && t.state != AnimationState::Finished
            }) {
                out.push(ActiveInfo {
                    node,
                    property: t.property_animation.property_id().name().to_string(),
                    is_animation: false,
                    start_ms: t.start_time * 1000.0,
                    end_ms: (t.start_time + t.property_animation.duration) * 1000.0,
                });
            }
            // A finished animation held by its fill (`Paused` at its end) is in force but no longer in flight.
            for a in s.animations.iter().filter(|a| {
                a.state != AnimationState::Canceled
                    && a.state != AnimationState::Finished
                    && !a.has_ended(self.time_s)
            }) {
                let end = match a.iteration_state {
                    KeyframesIterationState::Finite(cur, max) => {
                        (a.started_at + a.duration * (max - cur)) * 1000.0
                    }
                    KeyframesIterationState::Infinite(_) => f64::INFINITY,
                };
                out.push(ActiveInfo {
                    node,
                    property: a.name.to_string(),
                    is_animation: true,
                    start_ms: a.started_at * 1000.0,
                    end_ms: end,
                });
            }
        }
        out.sort_by(|a, b| {
            (a.node.raw().index, a.is_animation, &a.property).cmp(&(
                b.node.raw().index,
                b.is_animation,
                &b.property,
            ))
        });
        out
    }

    /// The latest end of every finite transition and animation, in seconds of document time
    /// (`finish_all` moves the clock there). `None` when nothing finite is in flight.
    pub(crate) fn latest_end_s(&self) -> Option<f64> {
        let mut latest: Option<f64> = None;
        let mut bump = |t: f64| latest = Some(latest.map_or(t, |l| l.max(t)));
        for s in self.set.sets.read().values() {
            for t in s
                .transitions
                .iter()
                .filter(|t| !matches!(t.state, AnimationState::Finished | AnimationState::Canceled))
            {
                bump(t.start_time + t.property_animation.duration);
            }
            for a in s
                .animations
                .iter()
                .filter(|a| matches!(a.state, AnimationState::Pending | AnimationState::Running))
            {
                if let KeyframesIterationState::Finite(cur, max) = a.iteration_state {
                    // `started_at` is the start of the current iteration.
                    bump(a.started_at + a.duration * (max - cur));
                }
            }
        }
        latest
    }

    /// One tick at the engine's time (already set): advance states, generate events, and report
    /// the elements the next pass must re-sample (`RECASCADE_SELF`).
    pub(crate) fn tick(&mut self, doc: &Document) -> TickOutcome {
        let now = self.time_s;
        let before = self.events.len();
        let mut out = TickOutcome::default();
        let mut dead: Vec<AnimationSetKey> = Vec::new();
        // Collected first: events borrow `self` mutably.
        let mut generated: Vec<(
            NodeId,
            Option<PseudoElement>,
            AnimationEventKind,
            String,
            f64,
        )> = Vec::new();
        {
            let mut sets = self.set.sets.write();
            // Sorted for a deterministic event order (hash order is not).
            let mut keys: Vec<AnimationSetKey> = sets.keys().cloned().collect();
            keys.sort_by_key(|k| (k.node.0, pseudo_name(&k.pseudo_element)));
            for key in keys {
                let Some(node) = resolve(doc, &key) else {
                    dead.push(key);
                    continue;
                };
                let Some(set) = sets.get_mut(&key) else {
                    continue;
                };
                let mut changed = false;
                for t in set.transitions.iter_mut() {
                    let name = t.property_animation.property_id().name().to_string();
                    if t.state == AnimationState::Pending {
                        if t.is_new {
                            t.is_new = false;
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::TransitionRun,
                                name.clone(),
                                transition_start_elapsed(t),
                            ));
                        }
                        if now >= t.start_time {
                            t.state = AnimationState::Running;
                            changed = true;
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::TransitionStart,
                                name.clone(),
                                transition_start_elapsed(t),
                            ));
                        }
                    }
                    if t.state == AnimationState::Running {
                        changed = true;
                        if t.has_ended(now) {
                            t.state = AnimationState::Finished;
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::TransitionEnd,
                                name,
                                t.property_animation.duration,
                            ));
                        }
                    }
                }
                for a in set.animations.iter_mut() {
                    let name = a.name.to_string();
                    if a.state == AnimationState::Pending && now >= a.started_at {
                        a.state = AnimationState::Running;
                        a.is_new = false;
                        changed = true;
                        let start = active_duration(a)
                            .map_or((-a.delay).max(0.0), |d| (-a.delay).clamp(0.0, d))
                            + 0.0;
                        generated.push((
                            node,
                            key.pseudo_element,
                            AnimationEventKind::AnimationStart,
                            name.clone(),
                            start,
                        ));
                    }
                    if a.state == AnimationState::Running {
                        changed = true;
                        let mut iterated = 0;
                        while a.iterate_if_necessary(now) {
                            iterated += 1;
                        }
                        if a.has_ended(now) {
                            let end = active_duration(a).unwrap_or(0.0);
                            a.state = if fills_forwards(a) {
                                AnimationState::Paused(a.current_iteration_end_progress())
                            } else {
                                AnimationState::Finished
                            };
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::AnimationEnd,
                                name,
                                end,
                            ));
                        } else if iterated > 0 {
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::AnimationIteration,
                                name,
                                current_iteration(a) * a.duration,
                            ));
                        }
                    }
                }
                if changed {
                    set.dirty = true;
                    if !out.changed.contains(&node) {
                        out.changed.push(node);
                    }
                }
            }
            for k in &dead {
                sets.remove(k);
            }
            out.active = sets
                .values()
                .any(ElementAnimationSet::needs_animation_ticks);
        }
        for (node, pseudo, kind, name, elapsed) in generated {
            self.push(node, &pseudo, kind, name, elapsed);
        }
        out.events = self.events.len() - before;
        out
    }

    /// After a style pass: `transitionrun` for transitions the pass created, `transitioncancel`
    /// and `animationcancel` for those it cancelled, then drop the cancelled entries and the
    /// emptied sets. (Events are generated here as well as at ticks so that a cancellation is
    /// reported even when it leaves nothing to tick.)
    pub(crate) fn after_pass(&mut self, doc: &Document) {
        let now = self.time_s;
        let mut generated: Vec<(
            NodeId,
            Option<PseudoElement>,
            AnimationEventKind,
            String,
            f64,
        )> = Vec::new();
        {
            let mut sets = self.set.sets.write();
            let mut keys: Vec<AnimationSetKey> = sets.keys().cloned().collect();
            keys.sort_by_key(|k| (k.node.0, pseudo_name(&k.pseudo_element)));
            for key in keys {
                let Some(node) = resolve(doc, &key) else {
                    sets.remove(&key);
                    continue;
                };
                let Some(set) = sets.get_mut(&key) else {
                    continue;
                };
                for t in set.transitions.iter_mut() {
                    let name = t.property_animation.property_id().name().to_string();
                    match t.state {
                        AnimationState::Pending if t.is_new => {
                            t.is_new = false;
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::TransitionRun,
                                name,
                                transition_start_elapsed(t),
                            ));
                        }
                        AnimationState::Canceled if !t.is_new => {
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::TransitionCancel,
                                name,
                                transition_elapsed(t, now),
                            ));
                        }
                        _ => {}
                    }
                }
                for a in set.animations.iter_mut() {
                    match a.state {
                        AnimationState::Canceled if !a.is_new => {
                            let active = active_duration(a);
                            let elapsed =
                                (now - (a.started_at - a.duration * current_iteration(a))).max(0.0);
                            generated.push((
                                node,
                                key.pseudo_element,
                                AnimationEventKind::AnimationCancel,
                                a.name.to_string(),
                                active.map_or(elapsed, |d| elapsed.min(d)),
                            ));
                        }
                        AnimationState::Pending
                        | AnimationState::Running
                        | AnimationState::Paused(_) => a.is_new = false,
                        _ => {}
                    }
                }
                set.clear_canceled_animations();
                if set.is_empty() {
                    sets.remove(&key);
                }
            }
        }
        for (node, pseudo, kind, name, elapsed) in generated {
            self.push(node, &pseudo, kind, name, elapsed);
        }
    }

    /// Take the queued events, dropping those of elements that are no longer connected.
    pub(crate) fn take_events(&mut self, doc: &Document) -> Vec<AnimationEvent> {
        let arena = doc.arena();
        std::mem::take(&mut self.events)
            .into_iter()
            .filter(|e| arena.contains(e.node) && arena.is_connected(e.node))
            .collect()
    }

    pub(crate) fn pending_events(&self) -> usize {
        self.events.len()
    }

    /// Move the sets, the time and the queued events of `old` into this (fresh) engine, e.g.
    /// across the stylist rebuild of an environment change; every set is re-applied by the next
    /// pass.
    pub(crate) fn adopt(&mut self, old: &mut AnimationEngine) {
        self.set = std::mem::take(&mut old.set);
        self.time_s = old.time_s;
        self.events.append(&mut old.events);
        self.mark_all_dirty();
    }
}

#[doc(hidden)]
pub fn key_for_testing(node: NodeId) -> AnimationSetKey {
    key_of(node, None)
}

// ---- the StyleBridge surface -------------------------------------------------------------------------

use crate::style::traverse::StyleBridge;
use style::invalidation::element::restyle_hints::RestyleHint;

impl StyleBridge {
    /// The document animation time in milliseconds (005's clock supplies it before each pass;
    /// it is constant for the whole pass, FR-065).
    pub fn set_animation_time_ms(&mut self, ms: f64) {
        self.anim.time_s = ms / 1000.0;
    }

    pub fn animation_time_ms(&self) -> f64 {
        self.anim.time_s * 1000.0
    }

    /// One animation tick at the current animation time: states advance, events are queued, and
    /// every element whose values change is marked for re-sampling by the next pass.
    pub fn tick_animations(&mut self, doc: &Document) -> TickOutcome {
        let out = self.anim.tick(doc);
        for &node in &out.changed {
            self.add_hint(doc, node, RestyleHint::RECASCADE_SELF);
        }
        out
    }

    /// Cancel the animations that never end (infinite iteration count) and mark their elements for
    /// re-sampling by the next pass (L-GEO-r9; the capture page's `end-state` policy). Returns the
    /// affected elements.
    pub fn cancel_infinite_animations(&mut self, doc: &Document) -> Vec<NodeId> {
        let nodes = self.anim.cancel_infinite(doc);
        for &node in &nodes {
            self.add_hint(doc, node, RestyleHint::RECASCADE_SELF);
        }
        nodes
    }

    /// After a rebuild with a fresh stylist (an environment change such as
    /// `prefers-reduced-motion`), the adopted animations were never compared with a previous
    /// style, so an animation that the new rules remove would keep running. Cancel every CSS
    /// animation whose name the element's `animation-name` in force no longer lists; returns the
    /// affected elements, marked for re-sampling.
    pub fn cancel_unstyled_animations(&mut self, doc: &Document) -> Vec<NodeId> {
        let mut nodes = Vec::new();
        for node in self.anim.elements_with_css_animations(doc) {
            let Ok(list) = self.computed_value(doc, node, "animation-name") else {
                continue;
            };
            let names: Vec<String> = list
                .split(',')
                .map(|n| n.trim().trim_matches('"').trim_matches('\'').to_owned())
                .filter(|n| !n.is_empty() && n != "none")
                .collect();
            if self.anim.cancel_unlisted(node, &names) {
                self.add_hint(doc, node, RestyleHint::RECASCADE_SELF);
                nodes.push(node);
            }
        }
        nodes
    }

    /// `needs_animation_ticks` (R-11): some transition or animation is pending or running.
    pub fn animations_need_ticks(&self) -> bool {
        self.anim.needs_ticks()
    }

    /// Take the queued transition and animation events (connected elements only).
    pub fn take_animation_events(&mut self, doc: &Document) -> Vec<AnimationEvent> {
        self.anim.take_events(doc)
    }

    /// The transitions and animations in force (probe input).
    pub fn active_animations(&self, doc: &Document) -> Vec<ActiveInfo> {
        self.anim.active_list(doc)
    }

    pub fn pending_animation_events(&self) -> usize {
        self.anim.pending_events()
    }

    /// The latest end of every finite transition and animation in flight (milliseconds of
    /// document time), for `finish_all`.
    pub fn latest_animation_end_ms(&self) -> Option<f64> {
        self.anim.latest_end_s().map(|s| s * 1000.0)
    }

    /// The elements with a transition or animation in force (running, delayed, or held by
    /// `animation-fill-mode: forwards|both`).
    pub fn animating_nodes(&self, doc: &Document) -> HashSet<NodeId> {
        self.anim.animating(doc)
    }

    /// Move the animation state of `old` into this bridge (a fresh stylist after an environment
    /// change keeps the running transitions and animations).
    pub fn adopt_animations_from(&mut self, old: &mut StyleBridge) {
        self.anim.adopt(&mut old.anim);
    }
}
