/// The union of `rects` (the default rect for none).
fn union_all(rects: &[LayoutRect]) -> LayoutRect {
    let Some(first) = rects.first() else {
        return LayoutRect::default();
    };
    let (mut l, mut t) = (first.origin.x, first.origin.y);
    let (mut r, mut b) = (
        first.origin.x + first.size.width,
        first.origin.y + first.size.height,
    );
    for x in &rects[1..] {
        l = l.min(x.origin.x);
        t = t.min(x.origin.y);
        r = r.max(x.origin.x + x.size.width);
        b = b.max(x.origin.y + x.size.height);
    }
    LayoutRect {
        origin: LayoutPoint { x: l, y: t },
        size: LayoutSize::from_edges(l, r, t, b),
    }
}

