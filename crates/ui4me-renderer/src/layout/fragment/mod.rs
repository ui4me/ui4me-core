/// One piece of a box broken across fragmentainers (015 FRAG-2b; plan §A3): the box fragment's rect is
/// the part of the box inside one fragmentainer, with the margins, borders and padding of a sliced edge
/// dropped (`box-decoration-break: slice`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FragmentPiece {
    /// 0 for the first piece of the box.
    pub index: u32,
    /// The last piece of the box.
    pub last: bool,
    /// Where this piece starts in the unfragmented box (border-box top = 0).
    pub block_offset: LayoutUnit,
    /// The unfragmented box's border-box height.
    pub whole_block_size: LayoutUnit,
    /// A repeated piece (table headers and footers; FRAG-2c): always `false` here.
    pub repeated: bool,
    /// A piece of an element split around a nested spanner (015 MC-2): the element's pieces are the pieces
    /// of all its boxes (one per row), numbered across them, `block_offset` and `whole_block_size` stitched.
    pub split: bool,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Fragment {
    pub id: FragmentId,
    pub parent: Option<FragmentId>,
    /// In `FragmentSpace::ParentBorderBox`.
    pub origin: LayoutPoint,
    pub size: LayoutSize,
    pub kind: FragmentKind,
    pub children: Vec<FragmentId>,
}

/// Immutable fragment tree of one layout pass (`Arc`-shared by consumers).
#[derive(Clone, Debug)]
pub struct FragmentTree {
    /// Layout epoch (the `layout` output of the revision tuple); one per published tree.
    pub epoch: u64,
    /// The single revision tuple of this tree (invariant 6); `None` until 005 supplies it.
    pub revision: Option<RevisionTuple>,
    pub viewport: Viewport,
    pub root: Option<FragmentId>,
    pub fragments: Vec<Fragment>,
    /// Box and text fragments per element, content order.
    pub node_to_fragments: HashMap<NodeId, Vec<FragmentId>>,
    pub paragraphs: Vec<Arc<FrozenParagraph>>,
    /// Text-decoration fragments, in paint order, grouped by line fragment (ascending `line`).
    pub decorations: Vec<DecorationFragment>,
    /// The viewport as a scroll container (FR-065): its `overflow`, scrollport and scrollable
    /// overflow in document space.
    pub viewport_scroll: ViewportScroll,
    /// `box_to_fragments` and `node_to_boxes`, content order (fragment-tree.md section 2).
    pub maps: maps::FragmentMaps,
    /// Stage diagnostics attached to the epoch (outcome O3).
    pub diagnostics: Vec<Status>,
    /// Document-space origin of each fragment (derived, kept for O(1) queries).
    document_origins: Vec<LayoutPoint>,
}

impl FragmentTree {
    pub fn empty(viewport: Viewport) -> Self {
        FragmentTree {
            epoch: 0,
            revision: None,
            maps: maps::FragmentMaps::default(),
            diagnostics: Vec::new(),
            viewport,
            root: None,
            fragments: Vec::new(),
            node_to_fragments: HashMap::new(),
            paragraphs: Vec::new(),
            decorations: Vec::new(),
            viewport_scroll: ViewportScroll::of_viewport(viewport),
            document_origins: Vec::new(),
        }
    }

    /// Tag this tree with its layout epoch and 005's revision tuple (invariant 6: one tuple per
    /// tree). Called once by the entry before publication; published trees are never mutated.
    pub fn stamp(&mut self, epoch: u64, revision: Option<RevisionTuple>) {
        self.epoch = epoch;
        self.revision = revision;
    }

    pub fn get(&self, id: FragmentId) -> &Fragment {
        &self.fragments[id.0 as usize]
    }

    pub fn origin_space(&self) -> FragmentSpace {
        FragmentSpace::ParentBorderBox
    }

    /// Border-box rect in document space (ICB origin; no scroll or transform).
    pub fn document_rect(&self, id: FragmentId) -> TaggedRect {
        let f = self.get(id);
        TaggedRect {
            rect: LayoutRect {
                origin: self.document_origins[id.0 as usize],
                size: f.size,
            },
            space: CoordinateSpace::Document,
        }
    }

    /// Recompute the document-space origins after the fragments' parent-relative origins changed
    /// (015 WM-1 `writing_mode::physical`). Parents precede their children in `fragments`.
    pub(crate) fn recompute_document_origins(&mut self) {
        for i in 0..self.fragments.len() {
            let f = &self.fragments[i];
            let o = match f.parent {
                Some(p) => {
                    let po = self.document_origins[p.0 as usize];
                    LayoutPoint {
                        x: po.x + f.origin.x,
                        y: po.y + f.origin.y,
                    }
                }
                None => f.origin,
            };
            self.document_origins[i] = o;
        }
    }

    pub fn fragments_of(&self, node: NodeId) -> &[FragmentId] {
        self.node_to_fragments
            .get(&node)
            .map(Vec::as_slice)
            .unwrap_or(&[])
    }

    /// An element repeated in the pieces of a broken table (a header or footer cell, 015 MC-2): its first
    /// occurrence in fragment order (its own box fragment or a copy) and how many occurrences there are. The
    /// reference reports the first occurrence's box, once per occurrence, from `getClientRects()`.
    pub fn repeated_first(&self, node: NodeId) -> Option<(FragmentId, usize)> {
        let copies = self.maps.repeated.get(&node).filter(|c| !c.is_empty())?;
        let own = self
            .fragments_of(node)
            .iter()
            .copied()
            .find(|i| matches!(self.get(*i).kind, FragmentKind::Box(_)))?;
        let first = copies
            .iter()
            .copied()
            .fold(own, |a, b| if b.0 < a.0 { b } else { a });
        Some((first, copies.len() + 1))
    }

    /// The element's first box fragment, else the union of its text fragments (document space).
    pub fn element_border_box(&self, node: NodeId) -> Option<TaggedRect> {
        if let Some((first, _)) = self.repeated_first(node) {
            return Some(self.document_rect(first));
        }
        let ids = self.fragments_of(node);
        if let Some(b) = ids
            .iter()
            .find(|i| matches!(self.get(**i).kind, FragmentKind::Box(_)))
        {
            // A box broken across fragmentainers (015 FRAG-2b): the union of its pieces.
            if let FragmentKind::Box(bf) = &self.get(*b).kind
                && bf.extras.piece.is_some()
            {
                let rects: Vec<LayoutRect> = self
                    .box_pieces(node)
                    .iter()
                    .map(|i| self.document_rect(*i).rect)
                    .collect();
                return Some(TaggedRect {
                    rect: union_all(&rects),
                    space: CoordinateSpace::Document,
                });
            }
            let r = self.document_rect(*b);
            if let FragmentKind::Box(bf) = &self.get(*b).kind
                && let Some(t) = &bf.extras.table_box
            {
                let o = r.rect.origin;
                return Some(TaggedRect {
                    rect: LayoutRect {
                        origin: LayoutPoint {
                            x: o.x + t.rect.origin.x,
                            y: o.y + t.rect.origin.y,
                        },
                        size: t.rect.size,
                    },
                    space: CoordinateSpace::Document,
                });
            }
            return Some(r);
        }
        // A table row or row group: its track rectangle is its border box.
        if let Some(t) = ids.iter().find(|i| matches!(&self.get(**i).kind, FragmentKind::TableTrack(t) if matches!(t.kind, TableTrackKind::Row | TableTrackKind::RowGroup))) {
            return Some(self.document_rect(*t));
        }
        // An inline box piece is its content area: its border box adds the padding and border
        // of the edges the piece carries (and always the top and bottom ones).
        let mut rects = ids.iter().map(|i| {
            let r = self.document_rect(*i).rect;
            match &self.get(*i).kind {
                FragmentKind::InlineBoxPiece(p) => {
                    let z = LayoutUnit::ZERO;
                    let on = self.piece_sides(*i);
                    let side = |k: usize, pad: LayoutUnit, bw: LayoutUnit| {
                        if on[k] { pad + bw } else { z }
                    };
                    let (t, rt, b, l) = (
                        side(0, p.padding.top, p.border_widths.top),
                        side(1, p.padding.right, p.border_widths.right),
                        side(2, p.padding.bottom, p.border_widths.bottom),
                        side(3, p.padding.left, p.border_widths.left),
                    );
                    let (x0, y0) = (r.origin.x - l, r.origin.y - t);
                    LayoutRect {
                        origin: LayoutPoint { x: x0, y: y0 },
                        size: LayoutSize::from_edges(
                            x0,
                            r.origin.x + r.size.width + rt,
                            y0,
                            r.origin.y + r.size.height + b,
                        ),
                    }
                }
                _ => r,
            }
        });
        let first = rects.next()?;
        let (mut l, mut t) = (first.origin.x, first.origin.y);
        let (mut r, mut b) = (
            first.origin.x + first.size.width,
            first.origin.y + first.size.height,
        );
        for x in rects {
            l = l.min(x.origin.x);
            t = t.min(x.origin.y);
            r = r.max(x.origin.x + x.size.width);
            b = b.max(x.origin.y + x.size.height);
        }
        Some(TaggedRect {
            rect: LayoutRect {
                origin: LayoutPoint { x: l, y: t },
                size: LayoutSize::from_edges(l, r, t, b),
            },
            space: CoordinateSpace::Document,
        })
    }

    /// The pieces of the element's box when it is broken across fragmentainers (015 FRAG-2b), in order.
    /// Which physical sides `[top, right, bottom, left]` of an inline box's piece carry its padding and border:
    /// the edges along the line are cut where the box continues on another line (physical left and right in
    /// horizontal text, top and bottom in a vertical line, the line's start at the bottom in `sideways-lr`;
    /// 015 WM-1). Every side for other fragments.
    pub fn piece_sides(&self, id: FragmentId) -> [bool; 4] {
        let FragmentKind::InlineBoxPiece(p) = &self.get(id).kind else {
            return [true; 4];
        };
        let vertical = self.get(id).parent.and_then(|l| match &self.get(l).kind {
            FragmentKind::Line(lf) => lf.vertical,
            _ => None,
        });
        let (s, e) = (p.has_start_edge, p.has_end_edge);
        match vertical.map(|v| v.orientation) {
            None | Some(crate::layout::writing_mode::LineOrientation::Horizontal) => {
                [true, e, true, s]
            }
            Some(crate::layout::writing_mode::LineOrientation::Clockwise) => [s, true, e, true],
            Some(crate::layout::writing_mode::LineOrientation::CounterClockwise) => {
                [e, true, s, true]
            }
        }
    }

    pub fn box_pieces(&self, node: NodeId) -> Vec<FragmentId> {
        let ids = self.fragments_of(node);
        let Some((first, split)) = ids.iter().find_map(|i| match &self.get(*i).kind {
            FragmentKind::Box(b) => b.extras.piece.map(|p| (b.box_id, p.split)),
            _ => None,
        }) else {
            return Vec::new();
        };
        ids.iter()
            .copied()
            .filter(|i| matches!(&self.get(*i).kind, FragmentKind::Box(b) if b.box_id == first || (split && b.extras.piece.is_some_and(|p| p.split))))
            .collect()
    }

    /// The box model of an element broken across fragmentainers as one unbroken box (what the reference
    /// browser's `offset*`, `client*` and box-model queries report; 015 FRAG-2b): placed at its first
    /// piece, as wide as it and as tall as the whole box, with the top edges of the first piece and the
    /// bottom ones of the last. `None` for an unbroken element.
    pub fn stitched_box(&self, node: NodeId) -> Option<StitchedBox> {
        let pieces = self.box_pieces(node);
        let (first, last) = (*pieces.first()?, *pieces.last()?);
        let (FragmentKind::Box(a), FragmentKind::Box(z)) =
            (&self.get(first).kind, &self.get(last).kind)
        else {
            return None;
        };
        let piece = a.extras.piece?;
        let origin = self.document_rect(first).rect.origin;
        let border = LayoutRect {
            origin,
            size: LayoutSize {
                width: self.get(first).size.width,
                height: piece.whole_block_size,
            },
        };
        let bw = LayoutEdges {
            top: a.border_widths.top,
            right: a.border_widths.right,
            bottom: z.border_widths.bottom,
            left: a.border_widths.left,
        };
        let pad = LayoutEdges {
            top: a.padding.top,
            right: a.padding.right,
            bottom: z.padding.bottom,
            left: a.padding.left,
        };
        let margins = LayoutEdges {
            top: a.margins.top,
            right: a.margins.right,
            bottom: z.margins.bottom,
            left: a.margins.left,
        };
        let inset = |r: LayoutRect, e: LayoutEdges| {
            let (l, t) = (r.origin.x + e.left, r.origin.y + e.top);
            LayoutRect {
                origin: LayoutPoint { x: l, y: t },
                size: LayoutSize::from_edges(
                    l,
                    r.origin.x + r.size.width - e.right,
                    t,
                    r.origin.y + r.size.height - e.bottom,
                ),
            }
        };
        let padding = inset(border, bw);
        let content = inset(padding, pad);
        Some(StitchedBox {
            first,
            border,
            padding,
            content,
            margins,
            border_widths: bw,
            padding_edges: pad,
        })
    }

    /// The element's first box fragment.
    pub fn box_fragment(&self, node: NodeId) -> Option<(&Fragment, &BoxFragment)> {
        self.fragments_of(node).iter().find_map(|i| {
            let f = self.get(*i);
            match &f.kind {
                FragmentKind::Box(b) => Some((f, b)),
                _ => None,
            }
        })
    }

    /// The decoration fragments of line fragment `line`.
    pub fn decorations_of(&self, line: FragmentId) -> &[DecorationFragment] {
        let a = self.decorations.partition_point(|d| d.line < line);
        let b = self.decorations.partition_point(|d| d.line <= line);
        &self.decorations[a..b]
    }

    /// Line fragments of the element's inline root box (0 when it is not one or has no text).
    pub fn line_count(&self, node: NodeId) -> usize {
        self.box_fragment(node)
            .map(|(f, _)| {
                f.children
                    .iter()
                    .filter(|c| matches!(self.get(**c).kind, FragmentKind::Line(_)))
                    .count()
            })
            .unwrap_or(0)
    }

    /// Text fragments owned by the element, content order.
    pub fn text_fragments_of(&self, node: NodeId) -> Vec<&Fragment> {
        self.fragments_of(node)
            .iter()
            .map(|i| self.get(*i))
            .filter(|f| matches!(f.kind, FragmentKind::Text(_)))
            .collect()
    }

    /// All fragments in tree (paint) order, root first.
    pub fn preorder(&self) -> Vec<FragmentId> {
        let mut out = Vec::new();
        let mut stack: Vec<FragmentId> = self.root.into_iter().collect();
        while let Some(id) = stack.pop() {
            out.push(id);
            stack.extend(self.get(id).children.iter().rev());
        }
        out
    }
}
