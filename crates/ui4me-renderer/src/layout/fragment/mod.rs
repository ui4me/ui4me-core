/// The viewport as a scroll container (FR-064, FR-065). Document space, no scroll offset.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ViewportScroll {
    /// The box whose `overflow` was propagated to the viewport; `None` for the default.
    pub source: Option<BoxId>,
    /// Used values (`visible` is `auto`, `clip` is `hidden`).
    pub overflow_x: OverflowMode,
    pub overflow_y: OverflowMode,
    /// The layout viewport: the initial containing block.
    pub scrollport: LayoutRect,
    /// The initial containing block united with the document's scrollable overflow.
    pub scrollable_overflow: LayoutRect,
}

impl ViewportScroll {
    /// The viewport of an empty document.
    pub fn of_viewport(viewport: Viewport) -> Self {
        let q = |px: f32| LayoutUnit::quantize(px as f64).value;
        let rect = LayoutRect {
            origin: LayoutPoint::default(),
            size: LayoutSize {
                width: q(viewport.width),
                height: q(viewport.height),
            },
        };
        ViewportScroll {
            source: None,
            overflow_x: OverflowMode::Auto,
            overflow_y: OverflowMode::Auto,
            scrollport: rect,
            scrollable_overflow: rect,
        }
    }
}

